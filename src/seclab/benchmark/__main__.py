"""Run the registered accuracy benchmark and emit JSON scoring."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import platform
import sys
from datetime import datetime, timezone
import hashlib
import uuid

from .catalog import CASES
from .production import execute_case
from .runner import load_executor, run_benchmark
from .report import render_markdown


def _run_metadata() -> dict[str, object]:
    from seclab.config import Toolchain
    sources = {}
    for source in ("src/seclab/benchmark/catalog.py", "src/seclab/benchmark/models.py",
                   "src/seclab/benchmark/production.py", "src/seclab/benchmark/runner.py",
                   "src/seclab/formal/ctl/model_checker.py", "src/seclab/formal/bmc/checker.py",
                   "src/seclab/formal/smt/solver.py", "src/seclab/formal/smt/evaluator.py",
                   "src/seclab/results/classifier.py"):
        path = Path(source)
        if path.is_file():
            sources[source] = hashlib.sha256(path.read_bytes()).hexdigest()
    return {
        "execution_id": str(uuid.uuid4()),
        "started_utc": datetime.now(timezone.utc).isoformat(),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "tools": Toolchain().summary(),
        "source_sha256": sources,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Run SecLab verification accuracy benchmark v1")
    parser.add_argument("--executor", help="Optional adapter as package.module:callable")
    parser.add_argument("--output", type=Path, help="Write JSON score report to this path")
    parser.add_argument("--markdown", type=Path, help="Write case-by-case Markdown report")
    parser.add_argument("--case", action="append", dest="case_ids", help="Run only this case ID; repeatable")
    parser.add_argument("--workspace", type=Path, default=Path("t/benchmark-runs"), help="Evidence workspace root")
    parser.add_argument("--execution-id", help="Stable run label; a fresh value is generated by default")
    args = parser.parse_args()
    executor = load_executor(args.executor) if args.executor else execute_case
    case_map = {case.case_id: case for case in CASES}
    unknown = set(args.case_ids or ()) - set(case_map)
    if unknown:
        parser.error("unknown case ID(s): " + ", ".join(sorted(unknown)))
    selected = tuple(case_map[case_id] for case_id in args.case_ids) if args.case_ids else CASES
    metadata = _run_metadata()
    if args.execution_id:
        metadata["execution_id"] = args.execution_id
    report = run_benchmark(selected, executor, workspace=args.workspace,
                           execution_id=str(metadata["execution_id"]), run_metadata=metadata)
    report_data = report.to_dict()
    report_data["run_metadata"] = metadata
    payload = json.dumps(report_data, indent=2, ensure_ascii=False)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload + "\n", encoding="utf-8")
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(render_markdown(report_data), encoding="utf-8")
    if not args.markdown:
        print(payload)
    return 1 if report.mismatches else 0


if __name__ == "__main__":
    raise SystemExit(main())
